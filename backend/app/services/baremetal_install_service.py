"""Unattended Enterprise Linux installs on physical BMC-managed hosts.

The BMC gets a generated Anaconda ISO over a short-lived opaque URL.  VM cloud
images are intentionally not accepted: qcow2/cloud-init is a libvirt workflow,
whereas a physical machine needs bootable installer media.
"""
import hmac
import os
import secrets
import shutil
import socket
import subprocess
from pathlib import Path
from urllib.parse import urlparse

from sqlalchemy.orm import Session

from app.config import settings
from app.models.bmh import BareMetalHost, BareMetalInstall
from app.schemas.bmh import BareMetalLinuxInstall
from app.schemas.task import TaskCreate
from app.services.baremetal_service import baremetal_service
from app.services.helper_service import HelperError, run_helper
from app.services.storage_service import storage_service
from app.services.task_service import task_service


class BareMetalInstallService:
    @property
    def _dir(self) -> Path:
        path = Path(settings.DATA_DIR) / "bmh-installs"
        path.mkdir(parents=True, exist_ok=True)
        os.chmod(path, 0o700)
        return path

    @staticmethod
    def _ks(data: BareMetalLinuxInstall) -> str:
        # Deliberately minimal and Anaconda-only.  The key is never persisted in
        # the database/API response; it only exists inside the generated ISO.
        repo = f"url --url={data.repo_url}\n" if data.repo_url else "cdrom\n"
        return f"""# Generated by VM Manager\ntext\nreboot\n{repo}lang en_US.UTF-8\nkeyboard us\ntimezone UTC --utc\nnetwork --bootproto=dhcp --activate\nfirewall --enabled --service=ssh\nselinux --enforcing\nfirstboot --disable\nignoredisk --only-use={data.target_disk}\nclearpart --all --initlabel --drives={data.target_disk}\nautopart --type=lvm\nrootpw --lock\nuser --name={data.admin_username} --groups=wheel --password=locked --iscrypted\nsshkey --username={data.admin_username} \"{data.ssh_authorized_key.strip()}\"\n%packages\n@^minimal-environment\nopenssh-server\n%end\n"""

    def _source_iso(self, db: Session, name: str) -> Path:
        iso = next((x for x in storage_service.list_isos(db) if x["name"] == name), None)
        if not iso:
            raise ValueError("Choose an installer ISO from Storage")
        path = Path(iso["path"]).resolve()
        if not path.is_file() or path.suffix.lower() != ".iso":
            raise ValueError("Selected installer ISO is unavailable")
        return path

    @staticmethod
    def _host_address(host: BareMetalHost) -> str:
        bmc_host = urlparse(host.bmc_address).hostname
        if not bmc_host:
            raise ValueError("BMC address has no host")
        sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            sock.connect((bmc_host, 443))
            ip = sock.getsockname()[0]
        finally:
            sock.close()
        if not ip or ip.startswith("127."):
            raise ValueError("Could not determine a BMC-reachable VM Manager address")
        return f"{ip}:{settings.PORT}"

    def create(self, db: Session, host: BareMetalHost, data: BareMetalLinuxInstall):
        if host.cluster_name or host.status not in ("available", "error"):
            raise ValueError(f"{host.name} is not available for a Linux install")
        if db.query(BareMetalInstall).filter(BareMetalInstall.host_id == host.id,
                                              BareMetalInstall.status.in_(("pending", "booting"))).first():
            raise ValueError(f"{host.name} already has an active install")
        if not shutil.which("mkksiso"):
            raise ValueError("mkksiso is not installed; install lorax on the VM Manager host")
        source = self._source_iso(db, data.iso_name)
        token = secrets.token_urlsafe(32)
        workdir = self._dir / token
        workdir.mkdir(mode=0o700)
        install = BareMetalInstall(host_id=host.id, name=data.name, installer_iso=str(source),
                                   target_disk=data.target_disk, token=token, workdir=str(workdir), status="pending")
        db.add(install)
        host.status, host.status_message = "provisioning", f"Preparing Linux install {data.name}"
        db.commit(); db.refresh(install)
        return task_service.start(db, TaskCreate(name=f"Install Linux {data.name} on {host.name}",
            type="baremetal_linux_install", target_type="bare_metal_host", target_id=host.id,
            target_name=host.name, description=f"Anaconda installer {source.name}"), self._boot, install.id, data)

    def _boot(self, db: Session, task, install_id: int, data: BareMetalLinuxInstall):
        install = db.get(BareMetalInstall, install_id)
        host = db.get(BareMetalHost, install.host_id)
        if not install or not host:
            raise RuntimeError("Install or bare-metal host was removed")
        workdir = Path(install.workdir)
        ks, output = workdir / "ks.cfg", workdir / "installer.iso"
        ks.write_text(self._ks(data)); os.chmod(ks, 0o600)
        task_service.update_progress(db, task.id, 20)
        try:
            run_helper(["build-bmh-iso", install.installer_iso, str(ks), str(output), str(os.getuid())],
                       timeout=30 * 60)
        except HelperError as e:
            install.status, install.status_message = "error", e.detail
            host.status, host.status_message = "error", e.detail
            db.commit()
            raise RuntimeError(e.detail) from e
        if not output.is_file():
            raise RuntimeError("The privileged ISO build completed without an installer ISO")
        task_service.update_progress(db, task.id, 70)
        url = f"http://{self._host_address(host)}/bmh-install/{install.token}/installer.iso"
        baremetal_service.client(db, host).boot_iso_once(url)
        install.status, install.status_message = "booting", "Installer ISO mounted; watch the BMC console"
        host.status_message = install.status_message
        db.commit(); task_service.update_progress(db, task.id, 95)
        return {"install_id": install.id, "status": install.status}

    def iso_for_token(self, db: Session, token: str):
        if not token:
            return None
        for install in db.query(BareMetalInstall).filter(BareMetalInstall.status.in_(("pending", "booting"))).all():
            if hmac.compare_digest(install.token, token):
                path = (Path(install.workdir) / "installer.iso").resolve()
                root = Path(install.workdir).resolve()
                return path if path.is_file() and root in path.parents else None
        return None

    def cancel(self, db: Session, install: BareMetalInstall):
        host = db.get(BareMetalHost, install.host_id)
        if host:
            try:
                bmc = baremetal_service.client(db, host); bmc.eject_media(); bmc.clear_boot_override(); bmc.power_off()
            except Exception:
                pass
            host.status, host.status_message = "available", None
        install.status, install.status_message = "cancelled", "Cancelled; virtual media ejected and host powered off"
        db.commit()


baremetal_install_service = BareMetalInstallService()
