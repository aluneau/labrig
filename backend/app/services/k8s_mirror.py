def resolve_kubeadm(rtr: str, minor: str, patch: Optional[str]) -> Dict[str, Any]:
    """On the router (internet): the Kubernetes patch (latest of `minor` unless given), the images
    `kubeadm config images list` gives for it, and Flannel's manifest. {version, images, flannel}"""
    from app.libvirt_client import libvirt_client
    from app.services import registry_router as rr
    tools = f"{rr.DATA}/tools"
    want = f"v{patch}" if patch else ""
    script = (
        "set -e\n"
        f"V={want}\n"
        f"[ -n \"$V\" ] || V=$(curl -fsSL --retry 5 https://dl.k8s.io/release/stable-{minor.lstrip('v')}.txt)\n"
        "case \"$V\" in v[0-9]*) ;; *) echo \"no Kubernetes release for " + minor + ": $V\" >&2; exit 3 ;; esac\n"
        f"mkdir -p {tools}\n"
        f"B={tools}/kubeadm-$V\n"
        "if [ ! -x $B ]; then curl -fsSL --retry 5 -o $B.part https://dl.k8s.io/release/$V/bin/linux/amd64/kubeadm"
        " && chmod 755 $B.part && mv $B.part $B; fi\n"
        "echo VERSION=$V\n"
        "$B config images list --kubernetes-version $V 2>/dev/null | sed 's/^/IMAGE=/'\n"
        f"echo FLANNEL=$(curl -fsSL --retry 5 {FLANNEL_MANIFEST} | base64 -w0)\n"
    )
    out = libvirt_client.agent_exec(rtr, "/bin/bash", ["-c", script], timeout=RESOLVE_TIMEOUT)
    if out["exitcode"] != 0:
        raise RuntimeError(f"Could not resolve the Kubernetes images on the router: "
                           f"{(out['stderr'] or out['stdout']).strip()[-800:]}")
    version, images, flannel = None, [], ""
    for line in out["stdout"].splitlines():
        key, _, value = line.partition("=")
        if key == "VERSION":
            version = value.strip()
        elif key == "IMAGE" and value.strip():
            images.append(value.strip())
        elif key == "FLANNEL":
            flannel = value.strip()
    if not version or not images:
        raise RuntimeError(f"Unexpected output while listing the Kubernetes images: {out['stdout'][-500:]}")
    if not flannel:
        raise RuntimeError(f"Could not download the Flannel manifest ({FLANNEL_MANIFEST}) on the router")
    manifest = base64.b64decode(flannel).decode()
    images += flannel_images(manifest)
    return {"version": version, "images": images, "flannel": flannel}


def flannel_images(manifest: str) -> List[str]:
    found: List[str] = []
    for m in re.finditer(r"^\s*image:\s*['\"]?([^\s'\"]+)", manifest, re.M):
        if m.group(1) not in found:
            found.append(m.group(1))
    return found


def mirror(group: Any, sources: List[str], progress: Any, label: str) -> Tuple[List[Dict[str, str]], List[str]]:
    """Copy `sources` into the group's registry: ([{source, mirror}], failed sources)"""
    from app.services import registry_images
    from app.services import registry_service as rs
    host = rs._hosts(rs._spec(group))[0]
    pairs: List[Tuple[str, str]] = []
    for src in sources:
        c = canonical(src)
        if all(c != p[0] for p in pairs):
            pairs.append((c, mirror_dest(c)))
    failed = registry_images.copy_list(group, pairs, progress, label)
    return [{"source": s, "mirror": f"{host}/{d}"} for s, d in pairs if s not in failed], failed
